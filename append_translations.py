if en_us_match:
    en_us_content = en_us_match.group(2)
    # Check existing keys in en_US to avoid duplicate
    existing_en_keys = [line.split(':')[0].strip().strip("'\"") for line in en_us_content.split('\n') if ':' in line]
    
    new_en_lines = []
    for k in translations.keys():
        if k not in existing_en_keys:
            # Escape quotes
            safe_k = k.replace("'", "\\'")
            new_en_lines.append(f"      '{safe_k}': '{safe_k}',")
    
    if new_en_lines:
        modified_en_us = en_us_match.group(1) + en_us_match.group(2) + "\n" + "\n".join(new_en_lines) + en_us_match.group(3)
        content = content.replace(en_us_match.group(0), modified_en_us)

